"""Generate the reusable sound-effects library with the ElevenLabs Sound Effects API.

Writes audio/sfx/<name>.mp3 (skips files that already exist) and audio/sfx/README.md.
Stops at the first quota / payment error so no credits are wasted on retries.
"""
import json, os, sys, urllib.error, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "audio/sfx")

SFX = [
    ("engine_cockpit_loop", 20, True, 0.6,
     "Constant low jet engine hum and air rush inside an airliner cockpit at cruise, steady, no voices, seamless loop"),
    ("alarm", 4, False, 0.7,
     "Airliner cockpit master caution alarm, repeating electronic beep chime warning, urgent"),
    ("button_click", 0.6, False, 0.8,
     "Single crisp click of a plastic push button on an aircraft autopilot panel, close up"),
    ("switch_toggle", 0.6, False, 0.8,
     "Single metal toggle switch flipped in an aircraft cockpit, sharp mechanical snap, close up"),
    ("gear_down", 5, False, 0.6,
     "Airliner landing gear extending: hydraulic whine, heavy mechanical clunk and thud as gear locks down, wind roar increases"),
    ("wind_descent", 8, False, 0.5,
     "Strong wind whistling and roaring around an airliner fuselage during a steep descent through clouds"),
    ("tire_screech", 2.5, False, 0.7,
     "Airliner tires touching down on a runway: short rubber screech chirp with a heavy thump"),
    ("reverse_thrust", 6, False, 0.6,
     "Jet engines roaring loudly in reverse thrust after airliner landing, powerful rising rumble, then slowing down"),
    ("cabin_applause", 6, False, 0.6,
     "Passengers applauding and cheering inside an airplane cabin after landing, relieved, enclosed space"),
]


def env():
    vals = {}
    for line in open(os.path.join(ROOT, ".env")):
        if "=" in line:
            k, v = line.strip().split("=", 1)
            vals[k] = v
    return vals


def main():
    key = env()["ELEVENLABS_API_KEY"]
    os.makedirs(OUT, exist_ok=True)
    for name, dur, loop, infl, prompt in SFX:
        path = os.path.join(OUT, f"{name}.mp3")
        if os.path.exists(path):
            print("skip", name)
            continue
        body = {"text": prompt, "duration_seconds": dur, "prompt_influence": infl,
                "model_id": "eleven_text_to_sound_v2"}
        if loop:
            body["loop"] = True
        req = urllib.request.Request(
            "https://api.elevenlabs.io/v1/sound-generation?output_format=mp3_44100_128",
            data=json.dumps(body).encode(),
            headers={"xi-api-key": key, "Content-Type": "application/json"})
        try:
            with urllib.request.urlopen(req, timeout=180) as r:
                data = r.read()
                cost = r.headers.get("character-cost") or r.headers.get("x-character-count")
        except urllib.error.HTTPError as e:
            msg = e.read().decode(errors="replace")
            print(f"STOP at {name}: HTTP {e.code} {msg}")
            sys.exit(2)
        open(path, "wb").write(data)
        print(f"ok {name} ({len(data)//1024} KB, cost header: {cost})")
    with open(os.path.join(OUT, "README.md"), "w", encoding="utf-8") as f:
        f.write("# SFX library (ElevenLabs Sound Effects API)\n\nReusable across videos. Generated by `tools/sfx_generate.py`.\n\n")
        f.write("| file | seconds | loop | prompt |\n|---|---|---|---|\n")
        for name, dur, loop, _, prompt in SFX:
            f.write(f"| `{name}.mp3` | {dur} | {'yes' if loop else ''} | {prompt} |\n")


if __name__ == "__main__":
    main()
